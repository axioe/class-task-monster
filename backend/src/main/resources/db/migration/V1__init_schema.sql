-- 우리 반 과제 몬스터 초기 스키마 (PostgreSQL)
-- 엔티티(com.classmonster.domain)와 1:1 로 맞춘다. 변경은 새 버전 파일(V2__...)로 추가한다.

CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id     VARCHAR(50)  NOT NULL,
    password     VARCHAR(255) NOT NULL,
    nickname     VARCHAR(30)  NOT NULL,
    role         VARCHAR(20)  NOT NULL,
    classroom_id BIGINT,
    created_at   TIMESTAMP(6) NOT NULL,
    updated_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_login_id UNIQUE (login_id),
    CONSTRAINT ck_users_role CHECK (role IN ('TEACHER', 'STUDENT'))
);

CREATE TABLE classroom (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50)  NOT NULL,
    monster_name  VARCHAR(30)  NOT NULL,
    growth_energy INTEGER      NOT NULL DEFAULT 0,
    stage         VARCHAR(20)  NOT NULL,
    teacher_id    BIGINT       NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_classroom_teacher FOREIGN KEY (teacher_id) REFERENCES users (id),
    CONSTRAINT ck_classroom_stage CHECK (stage IN ('EGG', 'BABY', 'GROWN'))
);

ALTER TABLE users
    ADD CONSTRAINT fk_users_classroom FOREIGN KEY (classroom_id) REFERENCES classroom (id);

CREATE TABLE assignment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id    BIGINT        NOT NULL,
    student_id      BIGINT        NOT NULL,
    title           VARCHAR(100)  NOT NULL,
    description     VARCHAR(1000),
    status          VARCHAR(30)   NOT NULL,
    submission_note VARCHAR(1000),
    teacher_comment VARCHAR(500),
    food_granted    BOOLEAN       NOT NULL DEFAULT FALSE,
    submitted_at    TIMESTAMP(6),
    reviewed_at     TIMESTAMP(6),
    created_at      TIMESTAMP(6)  NOT NULL,
    updated_at      TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_assignment_classroom FOREIGN KEY (classroom_id) REFERENCES classroom (id),
    CONSTRAINT fk_assignment_student FOREIGN KEY (student_id) REFERENCES users (id),
    CONSTRAINT ck_assignment_status CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'APPROVED', 'REVISION_REQUESTED'))
);

CREATE TABLE food_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT       NOT NULL,
    type        VARCHAR(20)  NOT NULL,
    consumed    BOOLEAN      NOT NULL DEFAULT FALSE,
    consumed_at TIMESTAMP(6),
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_food_item_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE TABLE expression_mission (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT       NOT NULL,
    mission_date DATE         NOT NULL,
    situation    VARCHAR(200) NOT NULL,
    created_at   TIMESTAMP(6) NOT NULL,
    updated_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_expression_mission_classroom FOREIGN KEY (classroom_id) REFERENCES classroom (id),
    CONSTRAINT uk_expression_mission_date UNIQUE (classroom_id, mission_date)
);

CREATE TABLE expression_option (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id BIGINT       NOT NULL,
    expression VARCHAR(100) NOT NULL,
    correct    BOOLEAN      NOT NULL,
    CONSTRAINT fk_expression_option_mission FOREIGN KEY (mission_id) REFERENCES expression_mission (id)
);

CREATE TABLE feeding_log (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id      BIGINT       NOT NULL,
    student_id        BIGINT       NOT NULL,
    situation         VARCHAR(200) NOT NULL,
    chosen_expression VARCHAR(100) NOT NULL,
    success           BOOLEAN      NOT NULL,
    food_type         VARCHAR(20),
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_feeding_log_classroom FOREIGN KEY (classroom_id) REFERENCES classroom (id),
    CONSTRAINT fk_feeding_log_student FOREIGN KEY (student_id) REFERENCES users (id)
);

CREATE TABLE growth_news (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT       NOT NULL,
    message      VARCHAR(200) NOT NULL,
    created_at   TIMESTAMP(6) NOT NULL,
    updated_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_growth_news_classroom FOREIGN KEY (classroom_id) REFERENCES classroom (id)
);

-- 조회 패턴에 맞춘 인덱스
CREATE INDEX idx_users_classroom ON users (classroom_id);
CREATE INDEX idx_classroom_teacher ON classroom (teacher_id);
CREATE INDEX idx_assignment_classroom_status ON assignment (classroom_id, status);
CREATE INDEX idx_assignment_student ON assignment (student_id);
CREATE INDEX idx_food_item_owner_consumed ON food_item (owner_id, consumed);
CREATE INDEX idx_expression_option_mission ON expression_option (mission_id);
CREATE INDEX idx_feeding_log_classroom ON feeding_log (classroom_id);
CREATE INDEX idx_feeding_log_student ON feeding_log (student_id);
CREATE INDEX idx_growth_news_classroom ON growth_news (classroom_id);
